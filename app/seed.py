# Пульс за последние 7 дней: старый -> новый
LAST7 = [
    (72, 6, 52),
    (71, 5, 48),
    (70, 5, 46),
    (72, 4, 44),
    (68, 6, 51),
    (69, 5, 45),
    (76, 4, 39),
]


def _daily_metrics(today: date) -> list[DailyMetric]:
    rows: list[DailyMetric] = []
    for i in range(30):
        day = today - timedelta(days=i)
        if i < len(LAST7):
            score, critical, response = LAST7[len(LAST7) - 1 - i]
        else:
            k = i - len(LAST7)
            score = 66 + (k * 5) % 13
            critical = 4 + (k * 3) % 5
            response = 40 + (k * 7) % 26
        rows.append(
            DailyMetric(
                day=day,
                score=score,
                critical_count=critical,
                avg_response_min=response,
                chats_count=9 + (i * 3) % 5,
                promises_kept_pct=50 + (i * 4) % 26,
            )
        )
    return rows


def seed(force: bool = False) -> bool:
    """Наполняет базу демо-данными. Возвращает True, если данные записаны."""
    db = SessionLocal()
    try:
        if not force and db.query(Employee).count():
            return False

        if force:
            for model in (ActionLog, Task, Finding, Promise, Message, Chat, Client, Employee, DailyMetric, Setting):
                db.query(model).delete()

        now = datetime.now().replace(second=0, microsecond=0)

        for eid, name, role, initials, since in EMPLOYEES:
            db.add(Employee(id=eid, name=name, role=role, initials=initials, since=since))

        for cid, name, kind, industry, contact, value in CLIENTS:
            db.add(
                Client(
                    id=cid,
                    name=name,
                    kind=kind,
                    industry=industry,
                    contact=contact,
                    crm_id=str(1000 + cid),
                    contract_value=value,
                )
            )
        db.flush()

        for spec in CHATS:
            messages = spec["messages"]
            last_at = now - timedelta(minutes=messages[-1]["ago"])
            chat = Chat(
                id=spec["id"],
                external_id=f"chat{1700 + spec['id']}",
                client_id=spec["client_id"],
                employee_id=spec["employee_id"],
                line=spec["line"],
                topic=spec["topic"],
                tags=spec["tags"],
                status="active",
                opened_at=now - timedelta(minutes=messages[0]["ago"]),
                last_activity=last_at,
                summary=spec["summary"],
                risk_amount=spec.get("risk_amount", 0),
            )
            db.add(chat)
            db.flush()

            msg_rows: list[Message] = []
            for m in messages:
                author = m["author"]
                if author == "employee":
                    author_name = next(e[1] for e in EMPLOYEES if e[0] == spec["employee_id"])
                elif author == "client":
                    author_name = next(c[1] for c in CLIENTS if c[0] == spec["client_id"])
                else:
                    author_name = "ПУЛЬС"
                row = Message(
                    chat_id=chat.id,
                    author=author,
                    author_name=author_name,
                    text=m["text"],
                    created_at=now - timedelta(minutes=m["ago"]),
                    meta={"flags": m.get("flags", [])},
                )
                db.add(row)
                msg_rows.append(row)
            db.flush()

            for p in spec.get("promises", []):
                source = msg_rows[p["source_idx"]] if p.get("source_idx") is not None else None
                db.add(
                    Promise(
                        chat_id=chat.id,
                        employee_id=spec["employee_id"],
                        text=p["text"],
                        due_at=now - timedelta(minutes=p["due_min_ago"]),
                        status=p["status"],
                        kept_at=(now - timedelta(minutes=p["kept_min_ago"]) if p.get("kept_min_ago") is not None else None),
                        source_message_id=(source.id if source else None),
                    )
                )

        for row in _daily_metrics(now.date()):
            db.add(row)

        db.add(
            Setting(
                key="presence",
                value={
                    "mode": "observer",
                    "silent_in_client_chat": True,
                    "helper_to_employee": True,
                    "escalate_to_owner": True,
                },
            )
        )
        db.add(
            Setting(
                key="notifications",
                value={
                    "daily_digest": True,
                    "daily_time": "09:00",
                    "weekly_report": True,
                    "weekly_day": "Пятница",
                    "instant_critical": True,
                },
            )
        )
        db.commit()

        from app.analysis import rebuild

        rebuild(db, now)
        db.commit()
        return True
    finally:
        db.close()
